#!/bin/sh
# 擬似乱数 rand の回帰 (2026-09-21 ・ #3572 で 1 つの名前へ統合 2026-09-22)。
#
# $1 = srava 実行体 / env: SRAVA_AGENT, SRAVA_CACHE_DIR。
#
# ---- 何を検定しているか ------------------------------------------------------------
# ① 決定性    同じ (a,b,n,s) を **別のキャッシュ dir で 2 回**走らせて一致すること。
#             ★ 同じ dir で 2 回流すのは検定にならない — 2 回目は必ずキャッシュ HIT なので、
#               生成器が壊れていても同じ値が返る (#3529 で踏んだ形)。
# ② 黄金値    ハードコードした期待列と一致すること。★★ これが **OS と標準ライブラリを
#             またぐ**唯一の検定 — 他の項目は「その機械の中で辻褄が合う」ことしか見ない。
#             mac / Windows でこの 1 行が落ちたら、生成器か写像が可搬でない。
# ③ 負の対照  シードを変えたら **違う**こと / 生成器を殺したら落ちること。
#             ⚠ ①② だけだと「常に同じ定数を返す実装」でも緑になる。
# ④ 整数か浮動か  規則は 1 つ (a と b が両方整数なら整数) で、それを **軸ごとに**適用する。
#             ★ 判別は **整数除算**で行う: 3/2 は整数なら 1 ・ 浮動小数点なら 1.5。
#               print の表示 (%.17g) では 3.0 も "3" になるので、見た目では区別できない。
# ⑤ 区間      整数は [a,b] **閉** (a も b も出る) ・ 浮動小数点は [a,b) **半開**。
# ⑥ 点群      第 1 引数が 2/3 要素の配列なら点群を作り、nverts == n ・ bbox が区間に収まる。
# ⑦ 明示エラー シード無し (arity) / a>b / n<0 / シードが浮動小数点 / 配列の長さ違い。
# ⑨ 統合      #3572: 次元は **第 1 引数の形** (要素数 0 / 2 / 3) が決める。出力型がその証拠。
#             ★ 旧名 rand_pt2d / rand_pt3d は **消えた** (別名は置かない)。
#             ⚠ 第 2 引数はマッチさせない — 食い違いは op の中で名指しする (ひさ 2026-09-22)。
#             ★★ **シードが省略できない**ことがこの op 群の設計そのものなので、
#               「3 引数で呼ぶと落ちる」は機能検定であって嫌がらせではない。
LC_ALL=C
export LC_ALL
SRAVA="$1"
D="${SRAVA_CACHE_DIR:?SRAVA_CACHE_DIR not set}"
# ★★ #3522: ハングの番犬 (共通)。詳細は test/srava_hangwatch.sh。
. "$(dirname "$0")/srava_hangwatch.sh"

run() {   # run <cache-suffix> <source>  → 出力全部
	rm -rf "$D-$1"
	SRAVA_CACHE_DIR="$D-$1" SRAVA_SOURCE="module(\"points.so\",{});
$2" "$SRAVA" 2>&1
}
v() {     # v <cache-suffix> <source>  → "V " 行の中身だけ (空白は落とす)
	# ⚠⚠ エラーは "V " で始まらないので、素の sed だと **空文字列**になる。
	#   すると「値が一致するか」の検定が *空 = 空* で通り、**壊れているのに緑**になる。
	#   2026-09-22 に実際に踏んだ: #3572 で消えた旧名 rand_pt3d を呼んでいる行が
	#   2 か所残っていたが、①の「同じ引数は同じ点群」も④の軸ごとの判定も緑だった
	#   (後者は awk が 0 行を回して bad=0 で抜けるため)。
	#   ⇒ **ここで止める**。エラーを期待する検定は v ではなく run を使う (chk_err)。
	_out=$(run "$1" "$2")
	case "$_out" in
	*"*** ERROR"*)
		# ⚠ v は `$( )` の中で呼ばれるので **exit では script を止められない**
		#   (部分シェルが死ぬだけ)。⇒ 印をファイルに残し、末尾で必ず赤にする。
		#   ★ 文言は stderr へ — stdout は呼び側の変数に入って見えなくなる。
		echo "RAND_FAIL: v $1 がエラーになった (検定が空振りするので止める):" >&2
		echo "$_out" >&2
		: > "$D-verror" ;;
	esac
	echo "$_out" | sed -n 's/^V //p' | tr -d ' '
}
n=0
chk() {   # chk <name> <got> <expected>
	[ "$2" = "$3" ] || { echo "RAND_FAIL: $1 が [$2] (期待 [$3])"; exit 1; }
	n=$((n+1))
}
chk_ne() {   # chk_ne <name> <got> <違っていてほしい値>
	[ "$2" != "$3" ] || { echo "RAND_FAIL: $1 が [$2] と一致してしまった (違うはず)"; exit 1; }
	n=$((n+1))
}
chk_err() {   # chk_err <name> <出力> <期待する部分文字列>
	case "$2" in
	*"$3"*) n=$((n+1)) ;;
	*) echo "RAND_FAIL: $1 がエラーにならない/文言が違う: $2" ; exit 1 ;;
	esac
}

# ---- ① 決定性 (別キャッシュで 2 回) ------------------------------------------------
A=$(v d1 'print("V", rand(0, 1000000, 8, 12345));')
B=$(v d2 'print("V", rand(0, 1000000, 8, 12345));')
chk "同じ引数は同じ結果 (整数)" "$A" "$B"

FA=$(v d3 'print("V", rand(0.0, 1.0, 8, 12345));')
FB=$(v d4 'print("V", rand(0.0, 1.0, 8, 12345));')
chk "同じ引数は同じ結果 (浮動小数点)" "$FA" "$FB"

PA=$(v d5 'print("V", vert(rand([0.0,0.0,0.0],[1.0,1.0,1.0], 4, 999), 2));')
PB=$(v d6 'print("V", vert(rand([0.0,0.0,0.0],[1.0,1.0,1.0], 4, 999), 2));')
chk "同じ引数は同じ点群" "$PA" "$PB"

# ---- ② 黄金値 (OS / 標準ライブラリをまたぐ検定) -------------------------------------
# ★★ 生成器 = xoshiro256** (種は splitmix64 で展開) ・ 整数は 2 冪マスク + 棄却。
#   どちらも uint64 の算術だけなので、**どの機械でもこの 8 個が出る**。
#   ⚠ ここが落ちたら「たまたま違う」ではない。生成器か写像が可搬でないか、意図せず列が
#     変わったかのどちらかで、後者なら points の cache_version を上げる必要がある
#     (上げないと古い cache が新しい列の顔で HIT する)。
chk "黄金値 (整数)" "$A" "[54427,428230,316296,450611,116296,331652,325273,908990]"

# ---- ③ 負の対照 --------------------------------------------------------------------
C=$(v n1 'print("V", rand(0, 1000000, 8, 12346));')
chk_ne "シードが違えば違う列" "$A" "$C"
# ⚠ 「n 個とも同じ値」= 生成器が進んでいない、を名指しで殺す。
U=$(v n2 'print("V", rand(0, 1000000, 6, 7)[0] == rand(0, 1000000, 6, 7)[5]);')
chk "同じ列の中で値が動いている" "$U" "0"

# ---- ④ 整数か浮動か (整数除算で判別) -----------------------------------------------
# ★ 区間を [3,3] に潰すと値は必ず 3。その 3 が整数か浮動小数点かだけが残る。
chk "a,b とも整数 → 整数"        "$(v t1 'print("V", rand(3, 3, 1, 5)[0] / 2);')"     "1"
chk "a が浮動 → 浮動"            "$(v t2 'print("V", rand(3.0, 3, 1, 5)[0] / 2);')"   "1.5"
chk "b が浮動 → 浮動"            "$(v t3 'print("V", rand(3, 3.0, 1, 5)[0] / 2);')"   "1.5"
# ★★ 軸ごとに独立に適用される (3 要素の rand の z だけ浮動小数点)。
#   vert(p,i) は座標を返すので、x は整数格子・z は連続であることを値で見る。
XZ=$(v t4 'var p = rand([0,0,0.0],[4,4,4.0], 6, 11);
print("V", vert(p,0));
print("V", vert(p,1));
print("V", vert(p,2));')
# x と y は整数格子 (小数点を含まない) ・ z は連続 (小数点を含む) はず。
echo "$XZ" | awk -F'[],[]' '
	{ for (i = 1; i <= NF; ++i) if ($i != "") v[++k] = $i }
	END {
		bad = 0
		for (j = 1; j <= k; ++j) {
			isf = (v[j] ~ /[.e]/)
			ax  = (j - 1) % 3
			if (ax < 2 && isf)  { print "軸 " ax " が浮動小数点: " v[j]; bad = 1 }
			if (ax == 2 && !isf) { print "軸 2 が整数: " v[j]; bad = 1 }
		}
		exit bad
	}' || { echo "RAND_FAIL: 軸ごとの整数/浮動の振り分け: $XZ"; exit 1; }
n=$((n+1))

# ---- ⑤ 区間 ------------------------------------------------------------------------
# 整数 [0,1] 閉: 値は 0 と 1 だけで、**両方とも出る** (シード固定なので確定した主張)。
Z=$(v r1 'print("V", rand(0, 1, 40, 3));')
echo "$Z" | tr -d '[]' | tr ',' '\n' | sort -u | tr '\n' ' ' | sed 's/ $//' > "$D-r1.set"
chk "整数 [0,1] は 0 と 1 の両方が出る (閉区間)" "$(cat "$D-r1.set")" "0 1"
rm -f "$D-r1.set"
# 整数 [7,7]: 幅 0 でも落ちない (全部 7)。
chk "整数 [7,7] は全部 7" "$(v r2 'print("V", rand(7, 7, 4, 1));')" "[7,7,7,7]"
# 浮動小数点 [2,5): すべて 2 <= v < 5。
F=$(v r3 'print("V", rand(2.0, 5.0, 200, 8));')
echo "$F" | tr -d '[]' | tr ',' '\n' | awk '
	($1 < 2 || $1 >= 5) { print "範囲外: " $1; bad = 1 }
	END { exit bad }' || { echo "RAND_FAIL: 浮動小数点が [2,5) に収まらない"; exit 1; }
n=$((n+1))
# 浮動小数点 [4.5,4.5): 幅 0 は 4.5 を返す (半開でも潰れた区間は端が出る)。
chk "浮動 [4.5,4.5) は全部 4.5" "$(v r4 'print("V", rand(4.5, 4.5, 3, 1));')" "[4.5,4.5,4.5]"
# n == 0 は空配列 (points3d([]) が空の点群を作れるのと同じ扱い)。
chk "n=0 は空配列" "$(v r5 'print("V", rand(0, 9, 0, 1));')" "[]"

# ---- ⑥ 点群 ------------------------------------------------------------------------
chk "3 軸の点数" "$(v p1 'print("V", nverts(rand([0.0,0.0,0.0],[1.0,1.0,1.0], 137, 2)));')" "137"
chk "2 軸の点数" "$(v p2 'print("V", nverts(rand([0.0,0.0],[1.0,1.0], 64, 2)));')" "64"
# ★ 整数配列を渡すと格子点になる (④ の規則が点群側でも同じであること)。
#   bbox が **2 成分**で返ること自体が「pt-cloud2d を作った」の証拠でもある (3D なら 3 成分)。
chk "2 軸の整数格子" "$(v p4 'print("V", bbox(rand([0,0],[1,1], 40, 4)));')" "[[0,0],[1,1]]"
# bbox が区間に収まる (連続のとき)。
echo "$(v p5 'print("V", bbox(rand([-2.0,0.0,10.0],[-1.0,1.0,11.0], 300, 6)));')" | \
	tr -d '[]' | tr ',' '\n' | awk '
	NR<=3 { lo[NR] = $1 } NR>3 { hi[NR-3] = $1 }
	END {
		want_lo[1] = -2; want_lo[2] = 0;  want_lo[3] = 10
		want_hi[1] = -1; want_hi[2] = 1;  want_hi[3] = 11
		for (i = 1; i <= 3; ++i) {
			if (lo[i] < want_lo[i] || hi[i] >= want_hi[i]) { print "軸 " i-1 " が区間外"; bad = 1 }
		}
		exit bad
	}' || { echo "RAND_FAIL: 3 軸の bbox が区間に収まらない"; exit 1; }
n=$((n+1))
# ⚠⚠ 法線は **付けない**。無い法線を (0,0,1) 等で埋めると Poisson も RANSAC もエラーに
#   ならずに走って静かに嘘の形を返す (ptCloud.h 冒頭の「既定の法線は作らない」)。
#   ★ 点群の法線を覗く op はまだ無いので、**書き出したファイルの列数**で見る
#     (3 列 = 法線なし / 6 列 = 法線あり。srava_points.sh ③ と同じ手)。
XYZ="$D-p6.xyz"
rm -f "$XYZ"
run p6 "export(\"$XYZ\", rand([0.0,0.0,0.0],[1.0,1.0,1.0], 4, 1));" >/dev/null 2>&1
chk "乱数の点群に法線は付かない (3 列)" "$(awk 'NR==1{print NF}' "$XYZ" 2>/dev/null)" "3"
chk "書き出した点数"                   "$(awk 'END{print NR}'   "$XYZ" 2>/dev/null)" "4"
rm -f "$XYZ"

# ---- ⑦ 明示エラー ------------------------------------------------------------------
# ★★★ シードは省略できない。3 引数は **routing が弾く** (記述子 nin=4 / nreq 無し)。
#   ★ #3570 段4: 個数は行の成立条件になったので、文言は「どれも受けない」を候補ごとに
#     並べる形 (段0 の列挙診断)。⇒ 「points: takes 4」と *誰が何個取るか* まで出る。
chk_err "シード省略 (rand)"      "$(run e1 'print("V", rand(0, 10, 4));')" \
                       "op 'rand' — no candidate takes 3 argument(s) (points: takes 4)"
chk_err "シード省略 (3 軸)" "$(run e2 'print("V", nverts(rand([0,0,0],[1,1,1], 4)));')" \
                       "op 'rand' — no candidate takes 3 argument(s) (points: takes 4)"
chk_err "a > b"        "$(run e3 'print("V", rand(10, 0, 4, 1));')"      "the range is empty"
chk_err "n が負"       "$(run e4 'print("V", rand(0, 10, -1, 1));')"     "must not be negative"
chk_err "シードが浮動" "$(run e5 'print("V", rand(0, 10, 4, 1.5));')"    "seed must be an integer"
chk_err "n が浮動"     "$(run e6 'print("V", rand(0, 10, 4.0, 1));')"    "n must be an integer"
# ★ #3572: a が 2 要素なら **行は rand#pt2d に決まる** ので、b の軸数違いとして言う
#   (「a が配列だから駄目」ではない — a の形が行を決め、b はその行の中で照合される)。
chk_err "b がスカラ"   "$(run e7 'print("V", nverts(rand([0,0], 10, 4, 1)));')" \
                       "a and b must each be an array of 2 numbers"
# ★ 「数か」は is_int() || is_flt() で訊いている (pigData.h) ので、**文字列も弾く**。
#   ⚠ 配列だけを弾く形だと get_flt() が 0 を返して *幅 0 の区間* として黙って通っていた。
chk_err "a が文字列"   "$(run e7b 'print("V", rand("abc", 10, 4, 1));')" "must be numbers"
# ⚠⚠ a=3 要素 / b=2 要素。マッチ関数は **第 1 引数しか見ない** ので行は rand#pt3d に
#   決まり、食い違いは op の中で名指しされる。★ 両方をマッチで見ると「どの行も成立
#   しない」= 場所を教えない文言に化ける (ひさ 2026-09-22 の設計理由そのもの)。
chk_err "軸数が違う"   "$(run e8 'print("V", nverts(rand([0,0,0],[1,1], 4, 1)));')" \
                       "an array of 3 numbers"
chk_err "軸の a > b"   "$(run e9 'print("V", nverts(rand([0,9,0],[1,1,1], 4, 1)));')" \
                       "the range of axis 1 is empty"
# ★ 要素数 1 / 4 の配列は **軸 1 本の行が引き取って**、形の話として名指しで断る。
#   ⚠ 行を用意せず routing に落とすと "no module can execute op 'rand' … accepted: ->value"
#     という *形について何も言わない* 文言になる (2026-09-22 実測)。
chk_err "要素数 1"     "$(run e10 'print("V", rand([0],[1], 4, 1));')" \
                       "an array of 2 or 3 numbers (one interval per axis), but it is an array of 1"
chk_err "要素数 4"     "$(run e10b 'print("V", rand([0,0,0,0],[1,1,1,1], 4, 1));')" \
                       "but it is an array of 4"

# ---- ⑧ in-proc の遅延ノード (★ 素の d_cast との違いが出る唯一の所) -------------------
# ★★ `is_int()` / `is_flt()` は **pigDataDelay が compact() で転送する**ゲートウェイ
#   (pigData.h)。map / lambda 由来の要素は **遅延ノードのまま** op に届くので、転送が
#   無いと「数でない」と判定されて `must be numbers` で落ちる。
# ⚠⚠ process 経路では値がテキスト化 → pig_value_parse で素の値に戻るので **気づけない**
#   (obt_array() が 2026-08-12 に踏んだのと同型)。⇒ **in-proc で回すことに意味がある**。
#
# ⚠⚠⚠ **スカラ引数では検定にならない** (2026-09-21 に測って分かった)。agent の引数種別検査が
#   先頭の引数に is_cache() を訊く時点で compact されるので、`rand(ii[0], …)` は転送を
#   外しても素通りする = **壊しても緑**。遅延のまま届くのは **配列引数の要素**だけ。
#   ⇒ ここは rand に **配列**を渡す形だけを使う (行 rand#pt2d)。
ip() {   # ip <cache-suffix> <source>  → "V " 行の中身だけ
	rm -rf "$D-$1"
	SRAVA_CACHE_DIR="$D-$1" SRAVA_SOURCE="module(\"points.so\",{exec_default:\"thread\"});
$2" "$SRAVA" 2>&1 | sed -n 's/^V //p' | tr -d ' '
}
# 整数の遅延要素 → 格子 (値が 0 と 1 だけなので bbox がちょうど区間になる)
chk "in-proc: 遅延要素が整数と分かる" \
	"$(ip i1 'print("V", bbox(rand(map([0,0], \(e){e;}), map([1,1], \(e){e;}), 40, 4)));')" \
	"[[0,0],[1,1]]"
# 浮動の遅延要素 → 連続 (★ 値を固定で書く。転送が無いとエラーで **空**になり赤くなる)
chk "in-proc: 遅延要素が浮動と分かる" \
	"$(ip i2 'print("V", bbox(rand(map([0.0,0.0], \(e){e;}), map([1.0,1.0], \(e){e;}), 40, 4)));')" \
	"[[0.028386148605554329,0.013182973462187331],[0.91779924071211638,0.97755356277447147]]"

# ---- ⑨ #3572: 次元は **第 1 引数の形**が決める (2026-09-22) --------------------------
# ★★ 行は rand / rand#pt2d / rand#pt3d の 3 本で、選ぶのは第 1 引数の要素数 (0 / 2 / 3)。
#   ⇒ **出力型そのもの**がどの行を通ったかの証拠になる (type_of で見る)。
chk "スカラ → 値の配列" "$(v u1 'print("V", type_of(rand(0, 10, 4, 1)));')"              "value"
chk "2 要素 → pt-cloud2d" "$(v u2 'print("V", type_of(rand([0,0],[1,1], 4, 1)));')"      "pt-cloud2d"
chk "3 要素 → pt-cloud3d" "$(v u3 'print("V", type_of(rand([0,0,0],[1,1,1], 4, 1)));')"  "pt-cloud3d"
# ★★ 統合前と **同じ値**であること (名前を替えただけで生成器は動いていない)。
#   ⚠ 黄金値は ② が持っているので、ここは「軸の規則が点群側でも同じ」を再確認する形にする。
chk "統合しても整数格子は同じ" "$(v u4 'print("V", bbox(rand([0,0,0],[1,1,1], 40, 4)));')" \
	"[[0,0,0],[1,1,1]]"
# ★ 旧名は **消えた** (別名は置かない = tube / tube_ruled と同じ作法)。
#   ⚠ ここが緑でないと「古い名前がまだ効く」= 利用者に 2 通りの書き方が残る。
chk_err "旧名 rand_pt3d は無い" "$(run u5 'print("V", nverts(rand_pt3d([0,0,0],[1,1,1], 4, 1)));')" \
                       "no module can execute op 'rand_pt3d'"
chk_err "旧名 rand_pt2d は無い" "$(run u6 'print("V", nverts(rand_pt2d([0,0],[1,1], 4, 1)));')" \
                       "no module can execute op 'rand_pt2d'"
# ★★ cold / warm で同じ行へ行くこと。⚠ routing が「値が読めたときだけ見る」形だと
#   1 回目と 2 回目で行が割れる (#3554 段2 が踏まないと決めた形)。
#   ⇒ **同じキャッシュ dir** で 2 回流して型が変わらないことで見る。
rm -rf "$D-u7"
W=$(SRAVA_CACHE_DIR="$D-u7" SRAVA_SOURCE='module("points.so",{});
print("V", type_of(rand([0,0],[1,1], 4, 1)));' "$SRAVA" 2>&1 | sed -n 's/^V //p')
W2=$(SRAVA_CACHE_DIR="$D-u7" SRAVA_SOURCE='module("points.so",{});
print("V", type_of(rand([0,0],[1,1], 4, 1)));' "$SRAVA" 2>&1 | sed -n 's/^V //p')
chk "cold と warm で同じ行" "$W2" "$W"
