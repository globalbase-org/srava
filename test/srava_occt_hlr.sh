#!/bin/sh
# ★★★ #3544 段 2: **陰線処理 (HLR)** — 立体から遮蔽を解いた 2D 図面を起こす。
#
# $1 = srava 実行体 / $2 = モジュール名 (.so)
# env: SRAVA_AGENT, SRAVA_CACHE_DIR。
#
# ---- 何で検証するか ------------------------------------------------------------------
# ★ 全部 **閉形式** (#3544 §4)。絵は見られないので、数えられる量だけで固定する:
#     立方体を [1,1,1] から … 可視 9 本 / 不可視 3 本
#     球                     … 稜 0 本 + 輪郭 1 本 ⇒ **ちょうど 1 本**
#     円柱 (r,h) を軸に垂直から … 稜 4 + 輪郭 2 = 6 本 ・ bbox = 2r x h
#
# ★★ ②の「ちょうど 1 本」は **2 つの誤りを同時に捕まえる**唯一の数:
#     0 本 … 輪郭 (OutLine) を載せていない ⇒ **球が図面から消える** (曲面に稜は無い)
#     2 本 … 継ぎ目 (RgNLine) を載せている ⇒ 図面に **表現の継ぎ目**が描かれる
#   ⇒ 「載せるものを 1 つ間違える」と必ずどちらかに倒れる。
#   ⚠ 実測 (2026-09-17): 視線が継ぎ目と重なると (球を -Y から見る) 輪郭が
#     V と OutV に **半円ずつ割れる** ので 2 本になる。⇒ 本数を見る検査は
#     *継ぎ目と重ならない視線* で行う。段 0 の「稜 0 / 輪郭 1」はこの条件下の値だった。
SRAVA="$1"
SO="${2:?module .so not given}"
D="${SRAVA_CACHE_DIR:?SRAVA_CACHE_DIR not set}"
# ★★ #3522: ハングの番犬 (共通・常時 ON)。詳細は test/srava_hangwatch.sh。
. "$(dirname "$0")/srava_hangwatch.sh"

fails=0
run() {   # run <cache-suffix> <source>
	rm -rf "$D-$1"
	SRAVA_CACHE_DIR="$D-$1" SRAVA_SOURCE="module(\"$SO\",{priority:99});
$2" "$SRAVA" 2>&1
}
vals() { echo "$1" | sed -n 's/^V //p'; }
chks() {  # chks <name> <got> <expected>
	if [ "$2" = "$3" ]; then echo "  ok  $1"
	else echo "FAIL: $1 が $2 (期待 $3)"; fails=$((fails+1)); fi
}
chkin() { # chkin <name> <haystack> <needle>
	case "$2" in
	*"$3"*) echo "  ok  $1" ;;
	*) echo "FAIL: $1 に \"$3\" が無い: $2"; fails=$((fails+1)) ;;
	esac
}

# ---- ⓪ 数える道具そのものの対照 (#3544 段 2 で足した nedges) ---------------------------
#   ⚠ これが狂っていると以下の本数が全部意味を失う。立方体の稜は 12 本 (共有は 1 本と数える)。
#     ★ 素朴に TopExp_Explorer で回すと 24 になる (2 面が共有するため) ⇒ 陰性対照でもある。
O=$(run n0 'print("V", nedges(box(2,2,2)));')
chks "⓪ nedges(box) は 12 (共有を畳む)" "$(vals "$O")" "12"

# ---- ① 立方体 — 可視 9 / 不可視 3 ------------------------------------------------------
#   ★ [1,1,1] の頂点から見ると、反対側の頂点に集まる 3 本だけが隠れる。
O=$(run h1 'var B = box(2,2,2);
print("V", nedges(hlr(B,[-1,-1,-1])));
print("V", nedges(hlr(B,[-1,-1,-1],"hidden")));')
# ⚠⚠ **値の分割だけ glob を止める** (2026-09-22)。
#   `set -- $(…)` の $( ) は **クォートできない** (単語分割が要る) のでパス名展開に掛かる。
#   比べる値は `[1,1,0]` 形 = glob の **文字クラス**なので、カレント (ビルド dir) に `1` という
#   名前のファイルが 1 つあるだけで `1` に化け、**「値が違う」という、それらしい文言で赤くなる**
#   (2026-09-21 に実際に踏んだ。⚠ PIG_TIMING は *ファイルパス* を取る env なので
#   `PIG_TIMING=1` と打つと `1` というファイルができる)。
#   ★★ **実行と分割を分ける**のが肝。`set -f; set -- $(cmd)` と囲うと -f が $( ) の中まで効き、
#     cmd がシェル関数だと *その中の glob* まで殺す (実測: count_tus → objs_of の
#     `CMakeFiles/*/link.txt` が読めず「全 0 本」になった)。⇒ 先に変数へ取ってから分割する。
_SPLIT_=$(vals "$O")
set -f
set -- $_SPLIT_
set +f
chks "① 立方体 可視 9 本" "$1" "9"
chks "① 立方体 不可視 3 本" "$2" "3"

# ---- ②★ 球 — 輪郭だけが 1 本 (載せるものを間違えたら必ず外れる) -----------------------
O=$(run h2 'var S = sphere(1.5);
print("V", nedges(hlr(S,[0,0,-1],[0,1,0])));
print("V", bbox(hlr(S,[0,0,-1],[0,1,0])));
print("V", nfaces(hlr(S,[0,0,-1],[0,1,0])));
print("V", area(hlr(S,[0,0,-1],[0,1,0])));')
_SPLIT_=$(vals "$O")
set -f
set -- $_SPLIT_
set +f
chks "②★ 球は ちょうど 1 本 (0=輪郭を落とした / 2=継ぎ目を描いた)" "$1" "1"
chks "② 球の輪郭は 半径 1.5 の円"  "$2" "[[-1.5,-1.5],[1.5,1.5]]"
chks "② 図面は 面を持たない"        "$3" "0"
chks "② 図面は 面積を持たない"      "$4" "0"

# ---- ③ 円柱 — 稜 4 + 輪郭 2 = 6 本 ・ bbox = 2r x h -----------------------------------
#   ★ 輪郭を落とすと 4 本になり bbox の幅が 0 になる (円柱の側面には稜が無い)。
O=$(run h3 'var C = cylinder(1,3);
print("V", nedges(hlr(C,[-1,0,0],[0,0,1])));
print("V", bbox(hlr(C,[-1,0,0],[0,0,1])));')
_SPLIT_=$(vals "$O")
set -f
set -- $_SPLIT_
set +f
chks "③ 円柱 可視 6 本 (稜 4 + 輪郭 2)" "$1" "6"
chks "③ 円柱の図面は 2r x h"            "$2" "[[-1,-1.5],[1,1.5]]"

# ---- ④★ 視線の**向き**が効く (符号の検査) ---------------------------------------------
#   ⚠ 立方体や球では **対称なので符号が検定できない** (裏から見ても同じ本数)。
#     ⇒ 前後が違う形を作る: 4x4x1 の板の上に 1x1x1 の小箱。
#       上から見る … 板の上面 4 + 小箱の上面 4 = 可視 8
#       下から見る … 板の下面 4 だけが可視 (小箱は板の陰) = 可視 4
O=$(run h4 'var U = union(box(4,4,1), translate(box(1,1,1),[1,1,1]));
print("V", nedges(hlr(U,[0,0,-1],[0,1,0])));
print("V", nedges(hlr(U,[0,0,1],[0,1,0])));')
_SPLIT_=$(vals "$O")
set -f
set -- $_SPLIT_
set +f
chks "④★ 上から見ると 可視 8 本" "$1" "8"
chks "④★ 下から見ると 可視 4 本 (小箱が板の陰に入る)" "$2" "4"

# ---- ⑤ up が図面の**回転**を決める ------------------------------------------------------
O=$(run h5 'var K = box(1,2,3);
print("V", bbox(hlr(K,[0,-1,0],[0,0,1])));
print("V", bbox(hlr(K,[0,-1,0],[1,0,0])));')
_SPLIT_=$(vals "$O")
set -f
set -- $_SPLIT_
set +f
chks "⑤ up=+Z なら 1 x 3" "$1" "[[-1,0],[0,3]]"
chks "⑤ up=+X なら 3 x 1 (図面が 90 度まわる)" "$2" "[[0,0],[3,1]]"

# ---- ⑥ 明示エラー 3 つ -----------------------------------------------------------------
#   ★ どれも **黙って既定へ逃げない**ことの検査。とくに up は、黙って別の向きに
#     差し替えると *図面の回転が黙って変わる* (段 0 の④)。
O=$(run h6a 'print("V", nedges(hlr(box(1,1,1),[0,0,-1])));')
chkin "⑥ up が視線と平行なら明示エラー" "$O" "parallel to the view direction"
O=$(run h6b 'print("V", nedges(hlr(box(1,1,1),[0,0,0],[0,1,0])));')
chkin "⑥ 視線が零ベクトルなら明示エラー" "$O" "must not be [0,0,0]"
O=$(run h6c 'print("V", nedges(hlr(box(1,1,1),[0,-1,0],[0,0,1],"dashed")));')
chkin "⑥ 知らない mode は明示エラー" "$O" "mode must be"
#   ⚠ 省略できる 2 つは **literal の種類**で見分ける (配列 = up / 文字列 = mode) ので、
#     同じ種類が 2 つ来たら「どちらのつもりか」は決められない ⇒ 黙って上書きせず断る。
O=$(run h6d 'print("V", nedges(hlr(box(1,1,1),[0,-1,0],[0,0,1],[1,0,0])));')
chkin "⑥ up を 2 つ渡したら明示エラー" "$O" "given twice"

# ---- ⑦ 型 — 出力は oc-cross2d (z=0 の簡易表現) ------------------------------------------
#   ★ bbox が **2 成分**で返ることがその現れ (#3544 段 1 の規約)。
#     ⇒ ②③⑤ の期待値が 2 成分であること自体が既にこの検査になっている。
#   ★★ ここでは **cast が通る**ことで見る — 降格は「本当に z=0 に居るときだけ」通るので、
#     図面が投影面に乗っていない実装なら明示エラーで落ちる。
O=$(run h7 'print("V", nedges(cast("oc-cross2d", hlr(sphere(1.5),[0,0,-1],[0,1,0]))));')
chks "⑦ 図面は本当に z=0 に居る (cast が通る)" "$(vals "$O")" "1"

# ---- ⑧ キャッシュ往復 — cold と warm で同じ答え -----------------------------------------
#   ⚠ 稜は **3D 曲線を持たない** (段 0 の実測) ので、ブロブの往復で欠けやすい。
rm -rf "$D-h8"
SRC="module(\"$SO\",{priority:99});
print(\"V\", nedges(hlr(cylinder(1,3),[-1,0,0],[0,0,1])));
print(\"V\", bbox(hlr(cylinder(1,3),[-1,0,0],[0,0,1])));"
C1=$(SRAVA_CACHE_DIR="$D-h8" SRAVA_SOURCE="$SRC" "$SRAVA" 2>&1 | sed -n 's/^V //p')
C2=$(SRAVA_CACHE_DIR="$D-h8" SRAVA_SOURCE="$SRC" "$SRAVA" 2>&1 | sed -n 's/^V //p')
chks "⑧ cold と warm で同じ答え" "$C2" "$C1"
chks "⑧ warm でも 6 本・2r x h" "$(echo "$C2" | tr '\n' ' ')" "6 [[-1,-1.5],[1,1.5]] "

if [ "$fails" = "0" ]; then echo "OCCT-HLR-OK ($SO)"; else echo "OCCT-HLR-FAIL ($fails fail)"; fi
exit "$fails"
