#!/bin/sh
# section(m, P, N[, mode]) — 断面 の回帰 (#3514 で occt へ配線したので 3 カーネル共通にした)。
#
# $1 = srava 実行体 / $2 = モジュール名 (.so) / $3 = 許容相対誤差
# $4 = "z" … Z 法線だけ検査 (manifold) / "all" … 6 軸 + 斜め / "analytic" … さらに解析球も (occt)
# env: SRAVA_AGENT, SRAVA_CACHE_DIR。
#
# ---- 固定するもの ------------------------------------------------------------------
# ★★ ① **3 要素配列の規約**。共面かどうかで「どの要素が答えか」が入れ替わる:
#       共面なし … [0] = 断面 ・ [1] [2] = 空集合
#       共面あり … [0] = 空集合 ・ [1] = 直下の極限 ・ [2] = 直上の極限
#   平面が面とちょうど重なると「平面上の断面」は面そのものになって **一意に決まらない**。
#   極限を別の要素で返すのがこの配列の意味 (docs の section の節)。
#   ⇒ 箱の天面 (z=2) と底面 (z=0) を必ず通す。ここが崩れると *黙って別の要素に答えが移る*。
#
# ★★ ② **面積だけでなく座標も**見る。2D 断面は切断平面の局所基底に置かれるので、面積が
#   合っていても基底の取り方が違えば bbox / extrude が食い違う。⇒ 断面を extrude して
#   **3D の bbox** で位置まで固定する (2D の bbox op を持たないカーネルがあるため)。
#   軸に平行な法線の基底は cgal の実装が事実上の規約: +x→(y,z) / -x→(-y,z) /
#   +y→(z,x) / -y→(-z,x) / +z→(x,y) / -z→(-x,y) (平面内の平行移動はしない)。
#   ⚠ #3533 で n∥y の行を **右手系に揃えた** (U x V = +n)。x と z は元から右手系だった。
#
# ★ ③ 解析曲面のまま切れること ($4="analytic")。球を高さ h で切った断面積は **π(r²-h²)**。
#   ⚠ メッシュ系は内接多角形なのでここは構造的に小さい値になる (r=2・h=1・seg=128 で
#     9.40914 / 真値 9.42478 = -0.17%)。許容を緩めて両方通すのは偽のテストになるので、
#     **B-rep のカーネルだけ**で検査する (srava_meshprops.sh / srava_distance_at.sh と同じ判断)。
SRAVA="$1"
SO="${2:?module .so not given}"
TOL="${3:-1e-9}"
MODE="${4:-z}"
D="${SRAVA_CACHE_DIR:?SRAVA_CACHE_DIR not set}"

# ★★ #3522: ハングの番犬 (共通)。詳細は test/srava_hangwatch.sh。
. "$(dirname "$0")/srava_hangwatch.sh"

run() {   # run <cache-suffix> <source>
	rm -rf "$D-$1"
	SRAVA_CACHE_DIR="$D-$1" SRAVA_SOURCE="module(\"$SO\",{priority:99});module(\"geomutils.so\",{});
$2" "$SRAVA" 2>&1
}
n=0
chk() {   # chk <name> <got> <expected>
	ok=$(awk -v g="$2" -v e="$3" -v t="$TOL" 'BEGIN{
		if(g==""){print 0; exit} d=g-e; if(d<0)d=-d; s=(e<0?-e:e); if(s<1)s=1;
		print (d/s <= t) ? 1 : 0 }')
	[ "$ok" = "1" ] || { echo "FAIL: $1 が $2 (期待 $3 ± 相対 $TOL)"; exit 1; }
	n=$((n+1))
}
chks() {  # chks <name> <got> <expected>   文字列の完全一致 (bbox 用)
	[ "$2" = "$3" ] || { echo "FAIL: $1 が $2 (期待 $3)"; exit 1; }
	n=$((n+1))
}
chkb6() {  # chkb6 <name> <got-bbox> <x0> <y0> <z0> <x1> <y1> <z1>   3D bbox の 6 値を許容付きで
	#   ★ #3536: occt の 2D は world に置かれた面なので bbox が 3 座標で返る。
	#     ⚠ **z も見る** — 置き場所を固定するのがこの検査の目的で、z を落としたら意味が消える。
	#     許容が要るのは Common の丸めと Bnd_Box の余裕 (実測 ±1.5e-7)。
	echo "$2" | tr -d '[]' | tr ',' ' ' | awk -v nm="$1" -v a="$3" -v b="$4" -v c="$5" \
	                                          -v d="$6" -v e="$7" -v f="$8" '
	{ k=0; for(i=1;i<=NF;i++) v[k++]=$i+0
	  if ( k != 6 ) { printf "FAIL: %s の bbox が %d 値 (3D の 6 値を期待)\n", nm, k; exit 1 }
	  t=1e-6
	  if ( (v[0]-a)^2+(v[1]-b)^2+(v[2]-c)^2+(v[3]-d)^2+(v[4]-e)^2+(v[5]-f)^2 > t*t ) {
	     printf "FAIL: %s が [%g,%g,%g,%g,%g,%g] (期待 [%g,%g,%g,%g,%g,%g])\n",
	            nm,v[0],v[1],v[2],v[3],v[4],v[5],a,b,c,d,e,f; exit 1 }
	}' || exit 1
	n=$((n+1))
}
chkb() {  # chkb <name> <got-bbox> <x0> <y0> <x1> <y1>   bbox の x/y 4 値を許容付きで見る
	#   ★ 厳密一致を要求できない相手 (occt は Common で作るので下位桁に丸めが出る) 用。
	echo "$2" | tr -d '[]' | tr ',' ' ' | awk -v nm="$1" -v a="$3" -v b="$4" -v c="$5" -v d="$6" '
	{ k=0; for(i=1;i<=NF;i++) v[k++]=$i+0
	  if ( k == 4 )      { g0=v[0]; g1=v[1]; g2=v[2]; g3=v[3] }
	  else if ( k == 6 ) { g0=v[0]; g1=v[1]; g2=v[3]; g3=v[4] }
	  else { printf "FAIL: %s の bbox が %d 値\n", nm, k; exit 1 }
	  t=1e-6
	  if ( (g0-a)^2+(g1-b)^2+(g2-c)^2+(g3-d)^2 > t*t ) {
	     printf "FAIL: %s が [%g,%g,%g,%g] (期待 [%g,%g,%g,%g])\n", nm,g0,g1,g2,g3,a,b,c,d; exit 1 }
	}' || exit 1
	n=$((n+1))
}

# ---- ① 3 要素配列の規約 ---------------------------------------------------------
O=$(run s1 '
var B = box(2,2,2);
var a = section(B,[0,0,1],[0,0,1]);   // 非共面 (中ほど)
var b = section(B,[0,0,2],[0,0,1]);   // ★ 共面 (天面)
var c = section(B,[0,0,0],[0,0,1]);   // ★ 共面 (底面)
print("VAL", area(a[0])); print("VAL", area(a[1])); print("VAL", area(a[2]));
print("VAL", area(b[0])); print("VAL", area(b[1])); print("VAL", area(b[2]));
print("VAL", area(c[0])); print("VAL", area(c[1])); print("VAL", area(c[2]));')
# ⚠⚠ **値の分割だけ glob を止める** (2026-09-22)。
#   `set -- $(…)` の $( ) は **クォートできない** (単語分割が要る) のでパス名展開に掛かる。
#   比べる値は `[1,1,0]` 形 = glob の **文字クラス**なので、カレント (ビルド dir) に `1` という
#   名前のファイルが 1 つあるだけで `1` に化け、**「値が違う」という、それらしい文言で赤くなる**
#   (2026-09-21 に実際に踏んだ。⚠ PIG_TIMING は *ファイルパス* を取る env なので
#   `PIG_TIMING=1` と打つと `1` というファイルができる)。
#   ★★ **実行と分割を分ける**のが肝。`set -f; set -- $(cmd)` と囲うと -f が $( ) の中まで効き、
#     cmd がシェル関数だと *その中の glob* まで殺す (実測: count_tus → objs_of の
#     `CMakeFiles/*/link.txt` が読めず「全 0 本」になった)。⇒ 先に変数へ取ってから分割する。
_SPLIT_=$(echo "$O" | sed -n 's/^VAL //p')
set -f
set -- $_SPLIT_
set +f
chk "非共面 [0] = 断面"   "$1" 4
chk "非共面 [1] = 空"     "$2" 0
chk "非共面 [2] = 空"     "$3" 0
chk "天面共面 [0] = 空"   "$4" 0
chk "★ 天面共面 [1] = 直下の極限" "$5" 4
chk "天面共面 [2] = 空"   "$6" 0
chk "底面共面 [0] = 空"   "$7" 0
chk "底面共面 [1] = 空"   "$8" 0
chk "★ 底面共面 [2] = 直上の極限" "$9" 4

# ---- ② 面積 + **座標** (Z 法線・全カーネル共通) ----------------------------------
#   原点にない箱で見る (原点にあると平行移動の取り違えが見えない)。
O=$(run s2 '
var B = translate(box(2,4,6),[1,2,3]);
var s = section(B,[0,0,5],[0,0,1])[0];
print("VAL", area(s));
print("BOX", bbox(extrude(s,1)));')
chk "z 断面の面積 2*4"  "$(echo "$O" | sed -n 's/^VAL //p')" 8
# ★★ #3526 (2026-09-13) + #3536 (2026-09-14): 断面は **切った場所に返る**。
#   ⇒ z=5 で切った断面を押し出すと **z=5 から** 立ち上がる。以前は黙って z=0 に戻っていた。
#   ★ 2026-09-14 に occt も揃った (#3536 で op_section の運搬を外した) ので **3 カーネル共通**。
#     ⚠ ここに `case "$SO"` の分岐を戻したくなったら、それは *また揃っていない* ということ。
chks "★ z 断面の位置 (切った場所・3 カーネル共通)" \
     "$(echo "$O" | sed -n 's/^BOX //p')" "[[1,2,5],[3,6,6]]"

# ---- ③ 穴のある断面 -------------------------------------------------------------
#   中空の箱を空洞の高さで切ると **穴の空いた 2D 領域**。穴を落とすと 16 になる。
O=$(run s3 '
var H = box(4,4,4) --- translate(box(2,2,2),[1,1,1]);
print("VAL", area(section(H,[0,0,2],[0,0,1])[0]));')
chk "★ 中空の箱の断面 16-4" "$(echo "$O" | sed -n 's/^VAL //p')" 12

# ---- ④ 退化した法線は明示エラー -------------------------------------------------
echo "$(run s4 'print("VAL", area(section(box(2,2,2),[0,0,1],[0,0,0])[0]));')" \
    | grep -qi "normal\|degenerate" || {
	echo "FAIL: 退化した法線 [0,0,0] が通った"; exit 1; }
n=$((n+1))

if [ "$MODE" = "z" ]; then
	echo "  note: $SO は Z 法線のみ対応なので ⑤⑥ は飛ばす"
	echo "SECTION-OK $SO ($n checks)"
	exit 0
fi

# ---- ⑤ 6 軸すべて — **基底の規約**をここで固定する ------------------------------
# ⚠⚠ 2026-09-14 (bench との同期): **extrude を通す形はここでは使えなくなった**。#3526 で断面が
#   切った場所に返るようになったので、x=2 / y=3 の断面は *world +Z を含む平面* に載る。そこへ
#   world +Z の押し出しをかけるのは明示エラー (掃引方向が面の中を向く) = ⑧で別に固定する。
#   ⇒ 基底の規約は **2D の局所座標**で直接見る (bbox は 2D には局所座標で答える)。値は
#     押し出していた頃の z 成分 (0,1) を落としただけで、規約そのものは 1 ビットも変えていない。
O=$(run s5 '
var B = translate(box(2,4,6),[1,2,3]);
print("BOX", bbox(section(B,[2,0,0],[ 1,0,0])[0]));
print("BOX", bbox(section(B,[2,0,0],[-1,0,0])[0]));
print("BOX", bbox(section(B,[0,3,0],[0, 1,0])[0]));
print("BOX", bbox(section(B,[0,3,0],[0,-1,0])[0]));
print("BOX", bbox(section(B,[0,0,5],[0,0,-1])[0]));
print("VAL", area(section(B,[2,0,0],[1,0,0])[0]));
print("VAL", area(section(B,[0,3,0],[0,1,0])[0]));')
i=0
for b in $(echo "$O" | sed -n 's/^BOX //p'); do i=$((i+1)); eval "B$i=\"$b\""; done
# ★★★ #3533: **3 カーネルが同じ表を見るようになった**。@section@ の出力は face3d で、
#   @bbox(face3d)@ は *world の 3 成分* を返す (ひさ判断 2026-09-14) ので、cg/mf/occt が
#   1 つの期待値表で足りる。⇒ ここで固定するのは基底ではなく **置き場所**。
#   ⚠ 2026-09-14 までここは cg/mf だけ「局所基底」を見ていた。#3533 で **見ている量そのものが
#     変わった** — 値だけ直したのではない。
#   ⚠⚠ 局所基底 (+x→(y,z) / -x→(-y,z) / +y→(z,x) / -y→(-z,x) / +z→(x,y) / -z→(-x,y)) は
#     これで **言語からは観測できなくなった** (bbox も centroid も world / 面積・周長は不変)。
#     残っているのは *キャッシュのバイト列* と *cast して降ろした後の SVG/DXF* だけ。
#     ⇒ 基底の規約は「利用者との契約」ではなく **表現の内部**になった。
#     ★ #3533 で表を @src/h/common/affine.h@ の 1 箇所へ畳み、n∥y の行を右手系に揃えた。
#       観測できない以上ここでは固定できないので、**ソースを数える検査** (srava_frame_table.sh)
#       を別に置いてある。
#   ⚠ occt は下位桁に丸めが出る (Common で作る + Bnd_Box が余裕を足す) ので許容付きで見る。
#   B = translate(box(2,4,6),[1,2,3]) は x∈[1,3] y∈[2,6] z∈[3,9]。
chkb6 "+x 断面は x=2 の平面上"  "$B1"  2 2 3   2 6 9
chkb6 "-x 断面も x=2 の平面上"  "$B2"  2 2 3   2 6 9
chkb6 "+y 断面は y=3 の平面上"  "$B3"  1 3 3   3 3 9
chkb6 "-y 断面も y=3 の平面上"  "$B4"  1 3 3   3 3 9
chkb6 "-z 断面は z=5 の平面上"  "$B5"  1 2 5   3 6 5
_SPLIT_=$(echo "$O" | sed -n 's/^VAL //p')
set -f
set -- $_SPLIT_
set +f
chk "x 断面の面積 4*6" "$1" 24
chk "y 断面の面積 2*6" "$2" 12

# ---- ⑥ 斜めの法線 (P を原点とする正規直交基底) ----------------------------------
#   単位箱を対角方向 [1,1,1] で中心を通るように切る。断面は正六角形で面積 = 3√3/2·(√2)² ... は
#   使わず、**カーネル間で一致すること**ではなく *この値* を焼き付ける (閉形式: 辺 √2 の正三角形を
#   角で落とした正六角形 = 3√3/2 · (√2)² / ... )。実測値 5.196152422706632 = 3√3。
O=$(run s6 'print("VAL", area(section(box(2,2,2),[1,1,1],[1,1,1])[0]));')
chk "斜め断面 = 3√3" "$(echo "$O" | sed -n 's/^VAL //p')" 5.196152422706632

# ---- ⑧ ★★ 断面が **切った平面に載っている**ことを、押し出しの可否で固定する (#3526) -----
#   z 法線の断面は world +Z へ押し出せる (②で位置まで見た)。x 法線の断面はその平面が +Z を
#   含むので **明示エラー**。⇒ 「断面が z=0 に戻っていない」ことがこの 2 つの差で言える。
#   ⚠ 面積だけでは検出できない (置き場所は面積を変えない)。
#   ★ #3536 で occt も運ばなくなったので **3 カーネル共通**にした (文言も同じ形で出る)。
#     ⚠ ここに occt を外す if を戻したくなったら、それは *また運んでいる* ということ。
echo "$(run s8 'var B = translate(box(2,4,6),[1,2,3]);
print("VAL", volume(extrude(section(B,[2,0,0],[1,0,0])[0],1)));')" \
    | grep -qi "sweep direction\|no well-defined inside" || {
	echo "FAIL: x=2 の断面が押し出せた (= 断面が z=0 へ戻っている疑い)"; exit 1; }
n=$((n+1))

if [ "$MODE" = "analytic" ]; then
	# ---- ⑦ ★ 解析曲面のまま切れる (B-rep のカーネルだけ) ----------------------
	#   球を高さ h で切った断面積は π(r²-h²)。⚠ これはメッシュ系では出ない値
	#   (内接多角形なので構造的に小さい)。
	O=$(run s7 '
var S = sphere(2);
print("VAL", area(section(S,[0,0,1],[0,0,1])[0]));
print("VAL", area(section(S,[0,0,0],[0,0,1])[0]));
print("VAL", area(section(S,[1,0,0],[1,0,0])[0]));
var C = cylinder(1,4);
print("VAL", area(section(C,[0,0,0],[0,0,1])[0]));
print("VAL", area(section(C,[0,0,0],[1,0,0])[0]));')
	_SPLIT_=$(echo "$O" | sed -n 's/^VAL //p')
	set -f
	set -- $_SPLIT_
	set +f
	chk "★ 球 h=1  π(4-1)"  "$1" 9.4247779607693797
	chk "★ 球 h=0  π·4"     "$2" 12.566370614359172
	chk "★ 球 x=1  π(4-1)"  "$3" 9.4247779607693797
	chk "円柱 横断面 π"      "$4" 3.1415926535897932
	chk "円柱 縦断面 2r·h"   "$5" 8
fi

echo "SECTION-OK $SO ($n checks)"
